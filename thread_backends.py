"""OS/architecture dependent threading layer, emitted as C by generator.py.

Everything that differs per platform lives here and nowhere in the C templates:
the engine only sees the tiny API declared in the generated fax_thread.h.
"""
from __future__ import annotations

from typing import Tuple

BACKENDS = ("win32", "pthread", "none")
ARCHES = {
    # name: (pointer bits, memory budget for optimizer workspaces in MB, max threads)
    "generic": (0, 0, 16),
    "x86": (32, 1000, 8),
    "x64": (64, 8192, 64),
    "arm64": (64, 8192, 64),
}

_COMMON_API = """
typedef void (*fax_thread_fn)(void *arg);

/* Logical CPUs usable by this process (>= 1). */
int fax_thread_cpu_count(void);

void fax_mutex_init(fax_mutex *mutex);
void fax_mutex_lock(fax_mutex *mutex);
void fax_mutex_unlock(fax_mutex *mutex);
void fax_mutex_destroy(fax_mutex *mutex);

/* Returns 0 on success.  fn(arg) runs on a new thread until it returns. */
int fax_thread_start(fax_thread *thread, fax_thread_fn fn, void *arg);
void fax_thread_join(fax_thread *thread);
"""


def _budget(arch: str) -> Tuple[str, str]:
    bits, mb, maxt = ARCHES[arch]
    if arch == "generic":
        mem = "((sizeof(void *) <= 4) ? 1000UL : 8192UL)"
    else:
        mem = "{}UL".format(mb)
    return mem, str(maxt)


def render(backend: str, arch: str) -> Tuple[str, str]:
    """Return (fax_thread.h, fax_thread.c) text for the chosen backend."""
    if backend not in BACKENDS:
        raise ValueError("unknown thread backend {!r}; use one of {}".format(backend, BACKENDS))
    if arch not in ARCHES:
        raise ValueError("unknown architecture {!r}; use one of {}".format(arch, sorted(ARCHES)))
    mem, maxt = _budget(arch)
    if backend == "none":
        maxt = "1"
    head = ["#ifndef FAX_THREAD_H", "#define FAX_THREAD_H", "",
            "/* Generated by generator.py (thread_backends.py). Do not edit by hand. */",
            "/* backend={} arch={} */".format(backend, arch), ""]
    head.append("#define FAX_THREADS_AVAILABLE {}".format(0 if backend == "none" else 1))
    head.append("#define FAX_MAX_THREADS {}".format(maxt))
    head.append("/* Memory (MB) the optimizer may use for per-thread workspaces. */")
    head.append("#define FAX_THREAD_MEMORY_MB {}".format(mem))
    head.append("")
    if backend == "win32":
        head += ["#define WIN32_LEAN_AND_MEAN", "#include <windows.h>", "",
                 "typedef struct fax_mutex { CRITICAL_SECTION section; } fax_mutex;",
                 "typedef void (*fax_thread_fn)(void *arg);",
                 "typedef struct fax_thread { HANDLE handle; fax_thread_fn fn; void *arg; } fax_thread;"]
        api = _COMMON_API.replace("typedef void (*fax_thread_fn)(void *arg);\n", "")
        src = """#include "fax_thread.h"

static DWORD WINAPI fax_thread_entry(LPVOID parameter)
{
    fax_thread *thread;
    thread = (fax_thread *)parameter;
    thread->fn(thread->arg);
    return 0;
}

int fax_thread_cpu_count(void)
{
    SYSTEM_INFO info;
    GetSystemInfo(&info);
    return (info.dwNumberOfProcessors > 0UL) ? (int)info.dwNumberOfProcessors : 1;
}

void fax_mutex_init(fax_mutex *mutex) { InitializeCriticalSection(&mutex->section); }
void fax_mutex_lock(fax_mutex *mutex) { EnterCriticalSection(&mutex->section); }
void fax_mutex_unlock(fax_mutex *mutex) { LeaveCriticalSection(&mutex->section); }
void fax_mutex_destroy(fax_mutex *mutex) { DeleteCriticalSection(&mutex->section); }

int fax_thread_start(fax_thread *thread, fax_thread_fn fn, void *arg)
{
    thread->fn = fn;
    thread->arg = arg;
    thread->handle = CreateThread((LPSECURITY_ATTRIBUTES)0, 0, fax_thread_entry,
                                  thread, 0, (LPDWORD)0);
    return (thread->handle != (HANDLE)0) ? 0 : 1;
}

void fax_thread_join(fax_thread *thread)
{
    WaitForSingleObject(thread->handle, INFINITE);
    CloseHandle(thread->handle);
    thread->handle = (HANDLE)0;
}
"""
    elif backend == "pthread":
        head += ["#include <pthread.h>", "",
                 "typedef struct fax_mutex { pthread_mutex_t mutex; } fax_mutex;",
                 "typedef void (*fax_thread_fn)(void *arg);",
                 "typedef struct fax_thread { pthread_t handle; fax_thread_fn fn; void *arg; } fax_thread;"]
        api = _COMMON_API.replace("typedef void (*fax_thread_fn)(void *arg);\n", "")
        src = """#ifndef _DEFAULT_SOURCE
# define _DEFAULT_SOURCE 1
#endif
#ifndef _POSIX_C_SOURCE
# define _POSIX_C_SOURCE 200809L
#endif
#include "fax_thread.h"
#include <unistd.h>

static void *fax_thread_entry(void *parameter)
{
    fax_thread *thread;
    thread = (fax_thread *)parameter;
    thread->fn(thread->arg);
    return (void *)0;
}

int fax_thread_cpu_count(void)
{
    long count;
    count = sysconf(_SC_NPROCESSORS_ONLN);
    return (count > 0L) ? (int)count : 1;
}

void fax_mutex_init(fax_mutex *mutex) { pthread_mutex_init(&mutex->mutex, (const pthread_mutexattr_t *)0); }
void fax_mutex_lock(fax_mutex *mutex) { pthread_mutex_lock(&mutex->mutex); }
void fax_mutex_unlock(fax_mutex *mutex) { pthread_mutex_unlock(&mutex->mutex); }
void fax_mutex_destroy(fax_mutex *mutex) { pthread_mutex_destroy(&mutex->mutex); }

int fax_thread_start(fax_thread *thread, fax_thread_fn fn, void *arg)
{
    thread->fn = fn;
    thread->arg = arg;
    return pthread_create(&thread->handle, (const pthread_attr_t *)0,
                          fax_thread_entry, thread) == 0 ? 0 : 1;
}

void fax_thread_join(fax_thread *thread)
{
    pthread_join(thread->handle, (void **)0);
}
"""
    else:
        head += ["typedef struct fax_mutex { int unused; } fax_mutex;",
                 "typedef void (*fax_thread_fn)(void *arg);",
                 "typedef struct fax_thread { int unused; } fax_thread;"]
        api = _COMMON_API.replace("typedef void (*fax_thread_fn)(void *arg);\n", "")
        src = """#include "fax_thread.h"

/* Single-threaded build (16-bit compilers, or --threads none). */
int fax_thread_cpu_count(void) { return 1; }
void fax_mutex_init(fax_mutex *mutex) { mutex->unused = 0; }
void fax_mutex_lock(fax_mutex *mutex) { (void)mutex; }
void fax_mutex_unlock(fax_mutex *mutex) { (void)mutex; }
void fax_mutex_destroy(fax_mutex *mutex) { (void)mutex; }
int fax_thread_start(fax_thread *thread, fax_thread_fn fn, void *arg)
{
    (void)thread; (void)fn; (void)arg;
    return 1;
}
void fax_thread_join(fax_thread *thread) { (void)thread; }
"""
    header = "\n".join(head) + "\n" + api + "\n#endif /* FAX_THREAD_H */\n"
    return header, src
